async function seed() {
  console.log(`Starting seed of ${booksData.length} books into public.books...`);

  for (const b of booksData) {
    const uuidSuffix = b.index.toString().padStart(12, "0");
    const bookId = `b0000000-0000-0000-0000-${uuidSuffix}`;
    const categoryId = categoryMap[b.categorySlug] || categoryMap.history;

    const row = {
      id: bookId,
      title: b.title,
      slug: b.slug,
      author: b.author,
      description: b.description,
      price: b.price,
      discount_price: null,
      stock: b.stock,
      category_id: categoryId,
      cover_front: b.image,
      cover_back: null,
      pages: b.pages,
      publisher: b.publisher,
      published_year: b.year,
      weight_grams: 350,
      sort_order: b.index,
      is_featured: b.featured,
      updated_at: new Date().toISOString(),
    };

    const { error } = await supabase.from("books").upsert(row, { onConflict: "id" });
    if (error) {
      console.error(`Error inserting book ${b.title}:`, error);
    } else {
      console.log(`✓ [${b.index}] ${b.title} (${bookId}) seeded.`);
    }
  }

  console.log("Seeding complete!");
}

seed();
